/**
 * Системные инструкции, дописываемые к вызовам Claude Code.
 *
 * Зачем: в headless-режиме (`claude -p`) интерактивный диалог недоступен, и
 * модель, столкнувшись с нехваткой информации, склонна молча достроить
 * недостающее предположениями. Для протокола «план → одобрение → выполнение»
 * это опасно: план одобряют, не зная, что внутри что-то угадано.
 *
 * Сам инструмент AskUserQuestion при этом запрещён через --disallowedTools,
 * так что «спросить» модель физически не может — остаётся написать вопросы
 * текстом, чего и требует инструкция ниже.
 */

/** Заголовок раздела, по которому мы распознаём открытые вопросы. */
export const OPEN_QUESTIONS_HEADING = "Открытые вопросы";

/**
 * Требование к формату итогового сообщения.
 *
 * Не косметика, а обязательная часть: в поле `result` ответа CLI попадает
 * ТОЛЬКО последнее сообщение модели. Без этого требования модель пишет раздел
 * с вопросами в промежуточном ходе, а в результат отдаёт что-то вроде
 * «ответ с открытыми вопросами уже выше» — и мост посчитал бы, что вопросов
 * нет. Это проверено на живых прогонах: без абзаца ниже раздел в `result`
 * не доходил.
 */
const SELF_CONTAINED_ANSWER = `ВАЖНО про формат итогового ответа: в результат попадает ТОЛЬКО твоё последнее сообщение. Оно должно быть самодостаточным — изложи в нём результат работы целиком. Не ссылайся на сказанное ранее фразами вроде «см. выше» или «описано в предыдущем сообщении».`;

const OPEN_QUESTIONS_RULE = `Если для задачи не хватает информации, не делай предположений и не пытайся спросить пользователя интерактивно — этот инструмент недоступен в данном режиме. Вместо этого прямо в тексте ответа выдели отдельный раздел \`## ${OPEN_QUESTIONS_HEADING}\` со списком того, что нужно уточнить, прежде чем план можно будет одобрить и выполнить.`;

/** Инструкция для plan_task. */
export const PLAN_SYSTEM_PROMPT = [
  OPEN_QUESTIONS_RULE,
  `${SELF_CONTAINED_ANSWER} Если вопросов нет, раздел \`## ${OPEN_QUESTIONS_HEADING}\` не добавляй вовсе — его наличие блокирует одобрение плана.`,
].join("\n\n");

/**
 * Инструкция для execute_task.
 *
 * Обычно не вступает в силу: --system-prompt-snapshot по умолчанию включён, и
 * при --resume отправляется системный промпт, записанный при первом запросе
 * сессии (то есть промпт plan_task). Передаём её всё равно — она применяется
 * после компактизации диалога и на случай, если снапшот отключат.
 */
export const EXECUTE_SYSTEM_PROMPT = [
  `Если по ходу выполнения выясняется, что информации не хватает, не угадывай и не пытайся спросить пользователя интерактивно — этот инструмент недоступен в данном режиме. Останови работу, не внося рискованных изменений, и перечисли недостающее разделом \`## ${OPEN_QUESTIONS_HEADING}\` в ответе.`,
  `${SELF_CONTAINED_ANSWER} Перечисли, что именно было сделано и какие файлы изменены.`,
].join("\n\n");
